def build_model(input_shape):
    # Inputs
    secret = layers.Input(shape=input_shape, name='secret_input')
    cover = layers.Input(shape=input_shape, name='cover_input')

    # Encoder
    encoder = make_encoder((s, s, 6))  # 6 channels input
    stego = encoder(layers.Concatenate()([secret, cover]))

    # Intermediate processing to get 64x64x3 for perceptual loss
    stego_for_loss = layers.Conv2D(3, 1, padding='same')(stego)
    stego_for_loss = layers.UpSampling2D(2)(stego_for_loss)  # 32x32 -> 64x64

    # Decoder
    decoder = make_decoder(stego.shape[1:])
    recovered_s = decoder(stego)

    # Combined model
    model = Model(
        inputs=[secret, cover],
        outputs=[stego_for_loss, recovered_s],  # Now both outputs are 64x64x3
        name='steganography_model'
    )

    model.output_names = ['stego_output', 'recovered_secret_output']

    # Compile
    # Compile
    model.compile(
        optimizer=optimizers.Adam(1e-4),
        loss={
            'stego_output': perceptual_loss,
            'recovered_secret_output': rev_loss
        },
        metrics={
            'stego_output': ['accuracy', calculate_psnr],
            'recovered_secret_output': ['accuracy', calculate_psnr]
        }
)
    return model

from tensorflow.image import psnr

def calculate_psnr(y_true, y_pred):
    """Calculate PSNR between true and predicted images"""
    return psnr(y_true, y_pred, max_val=1.0)

