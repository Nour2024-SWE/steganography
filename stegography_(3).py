# 9. Encoder with proper input shape
def make_encoder(input_shape):
    inputs = layers.Input(shape=input_shape)
    x = layers.Conv2D(64, 3, padding='same', activation='relu')(inputs)
    x = layers.MaxPooling2D(2)(x)  # Reduces to 32x32
    x = layers.Conv2D(128, 3, padding='same', activation='relu')(x)
    return Model(inputs, x)

# 10. Decoder with proper shape handling
def make_decoder(input_shape):
    inputs = layers.Input(shape=input_shape)
    x = layers.Conv2DTranspose(128, 3, padding='same', activation='relu')(inputs)
    x = layers.UpSampling2D(2)(x)  # Upsamples to 64x64
    x = layers.Conv2D(64, 3, padding='same', activation='relu')(x)
    x = layers.Conv2D(3, 1, padding='same', activation='sigmoid')(x)
    return Model(inputs, x)

# 11. Revised Loss Functions
def perceptual_loss(y_true, y_pred):
    """Modified to handle the stego output shape (32x32x128)"""
    # Resize y_pred to match VGG input (64x64x3)
    y_pred_resized = tf.image.resize(y_pred, [64, 64])  # Resize to 64x64
    y_pred_3channel = y_pred_resized[..., :3]  # Take first 3 channels

    y_true = tf.cast(y_true, tf.float32)
    y_pred_3channel = tf.cast(y_pred_3channel, tf.float32)

    true_feat = feat_extractor(y_true)
    pred_feat = feat_extractor(y_pred_3channel)
    return tf.reduce_mean((true_feat - pred_feat)**2)

def rev_loss(s_true, s_pred):
    """Reconstruction loss remains unchanged"""
    return 0.7 * tf.reduce_mean(tf.square(s_true - s_pred)) + 0.3 * (1 - tf.reduce_mean(tf.image.ssim(s_true, s_pred, max_val=1.0)))

